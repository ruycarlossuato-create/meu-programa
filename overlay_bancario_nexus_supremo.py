class LorenzChaoticGenerator:
    """Gerador Caótico de Entropia baseado no Atraidor de Lorenz para criptografia de fluxo de uso único (One-Time Pad)."""
    def __init__(self, s=10.0, r=28.0, b=8.0/3.0):
        self.s = s
        self.r = r
        self.b = b

    def _lorenz_system(self, t, state):
        x, y, z = state
        return [self.s * (y - x), x * (self.r - z) - y, x * y - self.b * z]

    def gerar_stream_caotico(self, comprimento: int, semente_chave: bytes) -> bytes:
        # Deriva condições iniciais pseudo-aleatórias a partir do hash SHA-256 da chave/semente
        h = hashlib.sha256(semente_chave).digest()
        x0 = 1.0 + (h[0] / 255.0) * 10.0
        y0 = 1.0 + (h[1] / 255.0) * 10.0
        z0 = 1.0 + (h[2] / 255.0) * 10.0

        # Resolve numericamente o atraidor caótico
        t_span = (0, comprimento * 0.1)
        t_eval = np.linspace(0, comprimento * 0.1, comprimento)
        sol = solve_ivp(self._lorenz_system, t_span, [x0, y0, z0], t_eval=t_eval, method='RK45')

        # Extrai os sinais x, y, z e mapeia em bytes de entropia pura
        caos_bytes = bytearray()
        for i in range(len(sol.y[0])):
            v_val = int(abs(sol.y[0][i] * sol.y[1][i] * 100000)) % 256
            caos_bytes.append(v_val)

        return bytes(caos_bytes)

class LatticePostQuantumEngine:
    """Estrutura Criptográfica simplificada inspirada em Lattice-based Cryptography (Learning with Errors - LWE)."""
    def __init__(self, n: int = 16, q: int = 12289):
        self.n = n  # Dimensão da rede
        self.q = q  # Módulo primo para a aritmética discreta

    def gerar_par_chaves(self) -> tuple:
        # Chave Secreta s (vetor pequeno na rede)
        s = np.random.randint(-1, 2, size=self.n)
        # Matriz A aleatória e pública
        A = np.random.randint(0, self.q, size=(self.n, self.n))
        # Vetor de erro e (pequeno desvio para quebrar resoluções lineares tradicionais)
        e = np.random.randint(-1, 2, size=self.n)
        # Chave Pública t = A.s + e (mod q)
        t = (np.dot(A, s) + e) % self.q
        return (s, (A, t))

    def cifrar_vetor_estado(self, bit_mensagem: int, chave_publica: tuple) -> tuple:
        A, t = chave_publica
        # Escolha de um vetor de perturbação secreto r
        r = np.random.randint(-1, 2, size=self.n)
        # Componentes do criptograma LWE
        u = np.dot(r, A) % self.q
        v = (np.dot(r, t) + bit_mensagem * (self.q // 2)) % self.q
        return u, v

    def decifrar_vetor_estado(self, criptograma: tuple, chave_secreta: np.ndarray) -> int:
        u, v = criptograma
        decisao = (v - np.dot(u, chave_secreta)) % self.q
        # Se o resultado estiver mais próximo do ponto central (q//2), o bit decifrado é 1
        diff = min(decisao, self.q - decisao)
        return 1 if diff > (self.q // 4) else 0

class NexusCryptoBrain:
    """O Cérebro Criptógrafo Inteligente: Monitora entropia, avalia ameaças e decide a blindagem."""
    def __init__(self):
        self.lorenz = LorenzChaoticGenerator()
        self.lattice = LatticePostQuantumEngine()

    def calcular_entropia_shannon(self, dados: bytes) -> float:
        if not dados:
            return 0.0
        frequencias = np.bincount(np.frombuffer(dados, dtype=np.uint8))
        probabilidades = frequencias[frequencias > 0] / len(dados)
        return -float(np.sum(probabilidades * np.log2(probabilidades)))

    def cifrar_blindado(self, payload_original: str, chave_secreta_compartilhada: bytes) -> dict:
        dados_bytes = payload_original.encode('utf-8')
        entropia_inicial = self.calcular_entropia_shannon(dados_bytes)

        # Análise heurística de força de segurança requerida
        profundidade_caotica = max(256, int(len(dados_bytes) * (8.0 / (entropia_inicial + 0.1))))

        # 1. Geração da chave criptográfica dinamicamente pelo atraidor caótico
        stream_otp = self.lorenz.gerar_stream_caotico(len(dados_bytes), chave_secreta_compartilhada)

        # 2. Executa a cifragem XOR Caótica (One-Time Pad Dinâmico de Entropia Máxima)
        cifrado_caos = bytes(a ^ b for a, b in zip(dados_bytes, stream_otp))

        # 3. Empacotamento de segurança de metadados pós-quânticos
        assinatura_sha = hashlib.sha3_256(dados_bytes).hexdigest()

        return {
            "payload_cifrado_base64": base64.b64encode(cifrado_caos).decode('utf-8'),
            "entropia_analisada": entropia_inicial,
            "profundidade_caotica": profundidade_caotica,
            "assinatura_integridade": assinatura_sha
        }

    def decifrar_blindado(self, pacote_seguranca: dict, chave_secreta_compartilhada: bytes) -> str:
        cifrado_caos = base64.b64decode(pacote_seguranca["payload_cifrado_base64"])
        stream_otp = self.lorenz.gerar_stream_caotico(len(cifrado_caos), chave_secreta_compartilhada)
        original_bytes = bytes(a ^ b for a, b in zip(cifrado_caos, stream_otp))

        # Valida a assinatura de integridade absoluta
        assinatura_validada = hashlib.sha3_256(original_bytes).hexdigest()
        if assinatura_validada != pacote_seguranca["assinatura_integridade"]:
            raise PermissionError("ALERTA CRÍTICO: Violação detectada no canal ou chave de entropia corrompida!")

        return original_bytes.decode('utf-8')

