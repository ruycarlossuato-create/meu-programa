import numpy as np
import json
from typing import Dict, List, Tuple

class VectorMemory:
    """Classe base para armazenamento e recuperação de memória vetorial."""
    def __init__(self, dimension: int = 128):
        self.dimension = dimension
        self.memory_store: Dict[str, np.ndarray] = {}
        self.meta_store: Dict[str, dict] = {}

    def add_memory(self, key: str, vector: np.ndarray, metadata: dict = None):
        if vector.shape[0] != self.dimension:
            raise ValueError(f"Dimensão do vetor deve ser {self.dimension}")
        self.memory_store[key] = vector
        self.meta_store[key] = metadata or {}

    def retrieve_similar(self, query_vector: np.ndarray, top_k: int = 3) -> List[Tuple[str, float, dict]]:
        if not self.memory_store:
            return []

        results = []
        for key, vector in self.memory_store.items():
            # Cálculo de similaridade por cosseno
            norm_q = np.linalg.norm(query_vector)
            norm_v = np.linalg.norm(vector)
            if norm_q == 0 or norm_v == 0:
                similarity = 0.0
            else:
                similarity = np.dot(query_vector, vector) / (norm_q * norm_v)
            results.append((key, float(similarity), self.meta_store[key]))

        results.sort(key=lambda x: x[1], reverse=True)
        return results[:top_k]

