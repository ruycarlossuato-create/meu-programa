import copy
import math

class ModularCloner:
    """Clonador Modular: Permite clonar e isolar subsistemas de memória independentes."""
    @staticmethod
    def clone(memory: VectorMemory) -> VectorMemory:
        new_mem = VectorMemory(dimension=memory.dimension)
        new_mem.memory_store = copy.deepcopy(memory.memory_store)
        new_mem.meta_store = copy.deepcopy(memory.meta_store)
        return new_mem

class FractalCloner:
    """Clonador Fractal: Clona a estrutura em diferentes níveis de resolução vetorial de forma auto-similar."""
    @staticmethod
    def clone_fractal(memory: VectorMemory, depth: int = 2) -> List[VectorMemory]:
        clones = []
        for i in range(1, depth + 1):
            scale_factor = 1.0 / math.sqrt(i)
            scaled_mem = VectorMemory(dimension=memory.dimension)
            for key, vec in memory.memory_store.items():
                scaled_mem.add_memory(f"{key}_fractal_lvl_{i}", vec * scale_factor, copy.deepcopy(memory.meta_store[key]))
            clones.append(scaled_mem)
        return clones

class DifferentialCloner:
    """Clonador Diferencial: Identifica e armazena apenas as mudanças e variações entre estados de memória."""
    @staticmethod
    def calculate_delta(base_mem: VectorMemory, target_mem: VectorMemory) -> Dict[str, np.ndarray]:
        deltas = {}
        for key, vec in target_mem.memory_store.items():
            if key in base_mem.memory_store:
                deltas[key] = vec - base_mem.memory_store[key]
            else:
                deltas[key] = vec
        return deltas

