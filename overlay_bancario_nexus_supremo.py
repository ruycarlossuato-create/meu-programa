import json

class SecureBankBridge:
    """Simulador de ponte de dados bancários segura usando criptografia AES (Fernet)."""
    def __init__(self):
        # Geração de chave simétrica padrão para simular o canal seguro de comunicação
        self.key = Fernet.generate_key()
        self.cipher = Fernet(self.key)

    def encrypt_transaction(self, transaction_data: dict) -> bytes:
        """Criptografa os dados da transação antes do envio."""
        raw_data = json.dumps(transaction_data).encode('utf-8')
        return self.cipher.encrypt(raw_data)

    def decrypt_transaction(self, encrypted_data: bytes) -> dict:
        """Decodifica com segurança a transação no destino."""
        decrypted_raw = self.cipher.decrypt(encrypted_data)
        return json.loads(decrypted_raw.decode('utf-8'))

